def main():
    if not DB.exists():
        print("ვერ ვიპოვე ბაზა: %s" % DB)
        print("ჩააგდე ეს ფაილი gap_finance საქაღალდეში (data/ საქაღალდის გვერდით).")
        return 1

    stamp = datetime.datetime.now().strftime("%Y%m%d-%H%M%S")
    backup = DB.with_name("gap_finance.backup-%s.db" % stamp)
    shutil.copy2(DB, backup)
    print("სარეზერვო ასლი: %s" % backup.name)

    con = sqlite3.connect(DB)
    con.row_factory = sqlite3.Row
    cur = con.cursor()

    row = cur.execute(
        "SELECT id, name FROM projects WHERE contract_no = ?", (CONTRACT_NO,)
    ).fetchone()
    if row:
        print("%s უკვე დამატებულია (პროექტი #%s). არაფერი შეცვლილა." % (CONTRACT_NO, row["id"]))
        con.close()
        return 0

    user = cur.execute("SELECT id FROM users ORDER BY id LIMIT 1").fetchone()
    user_id = user["id"] if user else None
    now = datetime.datetime.now().strftime("%Y-%m-%d %H:%M:%S")

    cur.execute(
        """INSERT INTO projects
           (name, contract_no, buyer, cpv_code, estimated_value, offered_price,
            duration_months, deadline, status, notes, created_at, created_by_id)
           VALUES (?,?,?,?,?,?,?,?,?,?,?,?)""",
        (
            PROJECT["name"], PROJECT["contract_no"], PROJECT["buyer"], PROJECT["cpv_code"],
            PROJECT["estimated_value"], PROJECT["offered_price"], PROJECT["duration_months"],
            PROJECT["deadline"], PROJECT["status"], PROJECT["notes"], now, user_id,
        ),
    )
    project_id = cur.lastrowid

    for phase, description in WORK_ITEMS:
        cur.execute(
            """INSERT INTO work_items
               (project_id, description, phase, contractor, contractor_contact,
                contractor_personal_id, deadline_text, deadline_date, estimated_cost,
                contract_amount, progress_percent, progress_status, note,
                created_at, created_by_id)
               VALUES (?,?,?,'','','','',NULL,0,0,0,'დაწყებამდე','',?,?)""",
            (project_id, description, phase, now, user_id),
        )

    con.commit()
    con.close()

    by_phase = {}
    for phase, _ in WORK_ITEMS:
        by_phase[phase] = by_phase.get(phase, 0) + 1

    print("")
    print("დაემატა პროექტი #%d — %s" % (project_id, CONTRACT_NO))
    print("სამუშაოები: %s (სულ %d)" % (
        ", ".join("%s ეტაპი — %d" % (p, n) for p, n in sorted(by_phase.items())),
        len(WORK_ITEMS),
    ))
    print("")
    print("გახსენი: http://localhost:8000/projects/%d" % project_id)
    print("(თუ აპი გაშვებულია — უბრალოდ განაახლე გვერდი.)")
    return 0


